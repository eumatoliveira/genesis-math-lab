import type { ProblemSpec } from '../types'

// Helper compact factory keeping all Number Theory entries rigorous and concise
function nt(
  id: string,
  code: string,
  title: string,
  status: ProblemSpec['status'],
  statusDetail: string,
  formulaLatex: string,
  description: string,
  variant: string,
  engine: ProblemSpec['engine'] = 'number-explorer',
  studyOrder?: number,
  extraParams?: ProblemSpec['parameters'],
  defaults?: Record<string, number>,
): ProblemSpec {
  return {
    id,
    code,
    title,
    category: 'number-theory',
    area: 'Teoria dos Números',
    status,
    statusDetail,
    formalTier: status === 'Resolvido' ? 'Demonstração Formalmente Verificada' : 'Conjectura',
    physicsTier: 'Analogia Exploratória',
    physicsRationale: 'Representação espectral/geométrica auxiliar sobre sequências aritméticas; sem realidade física presumida.',
    pillar: 'genesis',
    hermeticPrinciple: 'Ritmo & Correspondência nos padrões dos números inteiros',
    engine,
    variant,
    formulaLatex,
    description,
    philosophicalNote: 'Ramanujan & Wolfram: observar padrões inteiros visuais antes de postular identidades.',
    scientificBridge: 'Experimento finito reproduzível para detectar anomalias e classes de congruência.',
    studyOrder,
    defaultParams: defaults ?? { limit: 180, scale: 1.5 },
    parameters: extraParams ?? [
      { key: 'limit', label: 'Janela N', min: 40, max: 400, step: 10, defaultValue: 180 },
      { key: 'scale', label: 'Escala Visual', min: 0.5, max: 3.0, step: 0.1, defaultValue: 1.5 },
    ],
    openSourceHint: 'OEIS + SymPy + Python BigInt',
  }
}

